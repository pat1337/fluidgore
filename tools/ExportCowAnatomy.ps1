# Run after CowAnatomyModels.java. Writes only the generated runtime table.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$culture = [Globalization.CultureInfo]::InvariantCulture
function Number($value) { return ([double]$value).ToString('0.####', $culture) + 'F' }
function Rows($resolution) {
    $source = Join-Path $root "art/cow_anatomy_${resolution}x/piece_table.json"
    $rows = Get-Content -LiteralPath $source -Raw | ConvertFrom-Json
    foreach ($row in $rows) {
        # Head/limb canonical coordinates in the source table are trunk coordinates;
        # they must not be inserted into BEAST_HEAD or leg regions as-is.
        if ($row.group -match '^skeleton/(skull|limbs|spine/cervical|spine/tail)' -or $row.group -match '^head/' -or $row.name -eq 'udder') { continue }
        $bounds = [double[]]$row.canonical.Clone()
        $minimum = @(-5.0, -4.0, -8.0)
        $maximum = @(5.0, 4.0, 8.0)
        $valid = $true
        for ($a = 0; $a -lt 3; $a++) {
            $bounds[$a] = [Math]::Max($bounds[$a], $minimum[$a])
            $bounds[$a+3] = [Math]::Min($bounds[$a+3], $maximum[$a])
            if ($bounds[$a+3] -le $bounds[$a]) { $valid = $false }
        }
        if (-not $valid) { continue }
        $name = [string]$row.name
        $owner = $null
        if ($row.group -match '^thorax/lungs/') {
            $side = if ($row.group -match '/left_') { 'left' } else { 'right' }
            $owner = "${side}:lung"
            $name = 'lung'
        } elseif ($row.group -match '^abdomen/kidneys/(left|right)_kidney') {
            $owner = "$($Matches[1]):$name"
        } elseif ($row.group -match '^abdomen/liver') {
            $name = 'liver'
            $owner = ':liver'
        } elseif ($row.group -notmatch '^skeleton/') {
            $owner = ":$name"
        }
        $id = if ($null -eq $owner) { 'null' } else { '"' + $owner + '"' }
        $coords = ($bounds | ForEach-Object { Number $_ }) -join ', '
        "            p(Kind.$($row.kind), $coords, `"$name`", $id),"
    }
}
$fine = @(Rows 32)
$compact = @(Rows 16)
if ($fine.Count -lt 300 -or $compact.Count -lt 100) { throw 'Cow tables unexpectedly empty or incomplete' }
$source = @"
package dev.fluidgore.anatomy;

import dev.fluidgore.anatomy.Anatomy.Kind;
import dev.fluidgore.anatomy.Anatomy.Piece;

/** Generated by tools/ExportCowAnatomy.ps1 from the cow art's piece tables. Do not edit by hand.
 * Trunk only, in BEAST_TRUNK coordinates. Anatomical ownership keeps lobes and displaced kidneys together.
 * The 16x table supplies bounded loose-organ geometry where the 32x object exceeds the evidence budget.
 */
final class CowTrunk {
    private CowTrunk() {}

    static Piece[] pieces() {
        return new Piece[] {
$($fine -join "`n")
        };
    }

    static Piece[] compact() {
        return new Piece[] {
$($compact -join "`n")
        };
    }

    private static Piece p(Kind kind, float x0, float y0, float z0, float x1, float y1, float z1, String name, String owner) {
        return new Piece(kind, x0, y0, z0, x1, y1, z1, false, 1.0F, name, owner);
    }
}
"@
$target = Join-Path $root 'src/main/java/dev/fluidgore/anatomy/CowTrunk.java'
[IO.File]::WriteAllText($target, $source.Replace("`r`n", "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Output "Cow trunk exported: $($fine.Count) body cubes, $($compact.Count) compact cubes"
